"""Create a whole-project file inventory and exact-content duplicate report."""
from __future__ import annotations

import hashlib
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs/reports"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    hashes = defaultdict(list)
    counts = defaultdict(int)
    for path in ROOT.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT)
        if any(part in {".git", ".venv", "__pycache__"} for part in rel.parts):
            continue
        digest = sha256(path)
        suffix = path.suffix.lower() or "[no extension]"
        top = rel.parts[0]
        counts[(top, suffix)] += 1
        record = {"path": rel.as_posix(), "bytes": path.stat().st_size,
                  "sha256": digest, "top_level": top, "extension": suffix}
        rows.append(record)
        hashes[digest].append(record)
    rows.sort(key=lambda row: row["path"].casefold())
    inventory = OUT / "project_inventory.csv"
    import pandas as pd
    pd.DataFrame(rows).to_csv(inventory, index=False)
    duplicates = [{"sha256": digest, "bytes": items[0]["bytes"],
                   "paths": " | ".join(item["path"] for item in items)}
                  for digest, items in hashes.items() if len(items) > 1]
    pd.DataFrame(duplicates, columns=["sha256", "bytes", "paths"]).to_csv(OUT / "exact_duplicate_files.csv", index=False)
    lines = ["# Project folder inventory", "",
             f"Generated by `python src/project_file_inventory.py`. Enumerated {len(rows)} files with sizes and SHA-256 hashes.",
             "The environment folder `.venv`, Git internals `.git`, and Python bytecode caches are excluded from the content inventory; source-controlled project files, data, notebooks, reports, model artifacts and outputs are included.", "",
             "## Contents by top-level directory and file type", "",
             "| Directory | Extension | Files |", "|---|---|---:|"]
    for (top, ext), count in sorted(counts.items()):
        lines.append(f"| `{top}` | `{ext}` | {count} |")
    lines += ["", "## Exact duplicate files", "",
              f"The exact-content duplicate scan found {len(duplicates)} hash groups with more than one project path. Full paths and hashes are in `exact_duplicate_files.csv`. These files were not deleted; identical content does not alone establish that an artifact is safe to remove.", "",
              "## Output generations and disposition", "",
              "- `corrected_v1`, `corrected_v2`, `corrected_v3`, `corrected_v4_*`, and `corrected_v5_*` are versioned historical or current experiment outputs. They are preserved; legacy does not mean safe to delete.",
              "- `combined_temporal_results/` and same-year notebook outputs are observed-year/legacy comparisons, not valid future-forecast results.",
              "- Prior runs and audit CSV/JSON/Markdown files remain available as evidence. No generated artifact was removed during closure.", "",
              "## Work status and dependencies", "",
              "Implemented and evidenced work includes frozen target validation, source/group formulas, duplicate disposition rules, structural temporal leakage checks, saved-v4 metric recomputation and five-seed model comparisons. The five-seed feature-ablation runner status is recorded in its run-status CSV and is incorporated into the correction checklist.",
              "Open dependencies are primary NCRB source files/codebooks and year crosswalks, Railway subunit identities, administrative-boundary provenance, semantic missingness causes, and annual release/forecast issue dates. A conference-paper draft is new; no original manuscript/template was located.", ""]
    (OUT / "project_inventory.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Inventoried {len(rows)} files; exact-content duplicate hash groups: {len(duplicates)}")


if __name__ == "__main__":
    main()
